#!/usr/bin/env node
// Builds styles/tokens.css from styles/tokens.mjs and checks the tokens against DESIGN.md.
//
//   node scripts/tokens.mjs build            write styles/tokens.css
//   node scripts/tokens.mjs check            fail on stale CSS, missing tokens, or contrast below AA
//   node scripts/tokens.mjs check --usage    also report old token names, raw palette colours and
//                                            hex in components/ and composables/ (the migration list)
//   node scripts/tokens.mjs check --usage --strict    fail on those too
//   node scripts/tokens.mjs check --usage --dir ../vuetail-template/src    scan another project's
//                                            source instead (repeat --dir for several)
//
// No dependencies. Tailwind specifics the output relies on (verified against Tailwind 4.2):
//   - `@theme static` emits every variable, even ones no utility uses. Presets and runtime
//     customizers override them, so they must exist.
//   - Utilities read colours, radii, spacing and font sizes through var(), so overriding those
//     variables in a preset block retunes every existing class.
//   - Shadow utilities copy the theme value into the class at build time. The theme shadows
//     therefore point at --vt-shadow-1/2/3, which presets override.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { easing, presets, reducedMotion, status } from '../styles/tokens.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CSS_PATH = path.join(ROOT, 'styles', 'tokens.css');

// ─── CSS generation ────────────────────────────────────────────────────────────────────

const decl = (name, value) => `  ${name}: ${value};`;
const block = (selector, lines) => `${selector} {\n${lines.join('\n')}\n}`;
const indent = (text) => text.split('\n').map((l) => (l ? `  ${l}` : l)).join('\n');

const colorLines = (colors) => Object.entries(colors).map(([k, v]) => decl(`--color-${k}`, v));
const fontLines = (fonts) => Object.entries(fonts ?? {}).map(([k, v]) => decl(`--font-${k}`, v));
const radiusLines = (radius) => Object.entries(radius ?? {}).map(([k, v]) => decl(`--radius-${k}`, v));
const densityLines = (density) =>
  Object.entries(density ?? {}).map(([k, v]) => decl(k === 'text-control' ? '--text-control' : `--spacing-${k}`, v));
const motionLines = (motion) => Object.entries(motion ?? {}).map(([k, v]) => decl(`--vt-${k}`, v));
const shadowLines = (shadows) => Object.entries(shadows).map(([k, v]) => decl(`--vt-shadow-${k}`, v));

/** Tailwind's shadow scale, mapped onto the three elevation levels in DESIGN.md. */
const SHADOW_SCALE = { xs: 1, sm: 1, '': 1, md: 2, lg: 2, xl: 3, '2xl': 3 };

function darkBlocks(selector, lines) {
  // Explicit choice: data-theme="dark". System choice: no data-theme and a dark OS.
  const explicit = block(`${selector}[data-theme="dark"]`, [decl('color-scheme', 'dark'), ...lines]);
  const system = `@media (prefers-color-scheme: dark) {\n${indent(
    block(`${selector}:not([data-theme="light"])`, [decl('color-scheme', 'dark'), ...lines]),
  )}\n}`;
  return [explicit, system];
}

export function buildCss() {
  const ink = presets.ink;
  const out = [
    '/*',
    ' * VueTail tokens. GENERATED by scripts/tokens.mjs from styles/tokens.mjs: do not edit by hand.',
    ' * The contract behind every value is DESIGN.md.',
    ' *',
    ' * Default look: Ink. Presets: <html data-vt-preset="pine"> or "console".',
    ' * Theme: <html data-theme="dark"> or "light"; no attribute follows the OS.',
    ' */',
    '',
    block('@theme static', [
      ...fontLines(ink.fonts),
      ...colorLines({ ...ink.light.colors, ...status.light }),
      ...radiusLines(ink.radius),
      ...Object.entries(SHADOW_SCALE).map(([k, level]) => decl(k ? `--shadow-${k}` : '--shadow', `var(--vt-shadow-${level})`)),
      ...densityLines(ink.density),
      ...Object.entries(easing).map(([k, v]) => decl(`--ease-${k}`, v)),
      // Bare `transition-colors` and friends take the preset's motion, not Tailwind's 150ms curve.
      decl('--default-transition-duration', 'var(--vt-duration)'),
      decl('--default-transition-timing-function', 'var(--vt-ease)'),
    ]),
    '',
    block(':root', [
      decl('color-scheme', 'light'),
      ...shadowLines(ink.light.shadows),
      ...motionLines(ink.motion),
      ...Object.entries(easing).map(([k, v]) => decl(`--vt-ease${k === 'standard' ? '' : `-${k}`}`, v)),
    ]),
    '',
    `@layer base {\n${indent(block(':where(:focus-visible)', [decl('outline', '2px solid var(--color-ring)'), decl('outline-offset', '2px')]))}\n}`,
    '',
    // Reserve the scrollbar's width, so locking scroll under a modal does not shift the page.
    `@layer base {\n${indent(block(':where(html)', [decl('scrollbar-gutter', 'stable')]))}\n}`,
    '',
    ...darkBlocks(':root', [...colorLines({ ...ink.dark.colors, ...status.dark }), ...shadowLines(ink.dark.shadows)]),
  ];

  for (const [name, p] of Object.entries(presets)) {
    if (name === 'ink') continue;
    const sel = `:root[data-vt-preset="${name}"]`;
    out.push(
      '',
      `/* ── ${name[0].toUpperCase()}${name.slice(1)} ── */`,
      block(sel, [
        ...fontLines(p.fonts),
        ...radiusLines(p.radius),
        ...densityLines(p.density),
        ...motionLines(p.motion),
        ...colorLines(p.light.colors),
        ...shadowLines(p.light.shadows),
      ]),
      '',
      ...darkBlocks(sel, [...colorLines(p.dark.colors), ...shadowLines(p.dark.shadows)]),
    );
  }
  // Last, and as specific as a preset block, so it wins in Pine and Console too.
  out.push(
    '',
    `@media (prefers-reduced-motion: reduce) {\n${indent(block(':root,\n:root[data-vt-preset]', motionLines(reducedMotion)))}\n}`,
  );
  return out.join('\n') + '\n';
}

// ─── Contrast ──────────────────────────────────────────────────────────────────────────

function parseColor(value) {
  const hex = value.match(/^#([0-9a-f]{6})$/i);
  if (hex) return { rgb: [0, 2, 4].map((i) => parseInt(hex[1].slice(i, i + 2), 16)), a: 1 };
  const rgb = value.match(/^rgb\(\s*(\d+)\s+(\d+)\s+(\d+)\s*(?:\/\s*([\d.]+)\s*)?\)$/);
  if (rgb) return { rgb: [+rgb[1], +rgb[2], +rgb[3]], a: rgb[4] === undefined ? 1 : +rgb[4] };
  throw new Error(`Unparseable colour: ${value}`);
}
const over = (fg, bg) => fg.rgb.map((c, i) => c * fg.a + bg[i] * (1 - fg.a));
const luminance = (rgb) =>
  rgb
    .map((c) => c / 255)
    .map((c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4))
    .reduce((sum, c, i) => sum + c * [0.2126, 0.7152, 0.0722][i], 0);

/** Contrast of fg on bg, with translucent backgrounds composited over the page ground. */
function contrast(fg, bg, ground) {
  const base = parseColor(ground).rgb;
  const b = over(parseColor(bg), base);
  const f = over(parseColor(fg), b);
  const [x, y] = [luminance(f), luminance(b)];
  return (Math.max(x, y) + 0.05) / (Math.min(x, y) + 0.05);
}

const STATUS = ['success', 'warning', 'danger', 'info'];
const PAIRS = [
  ['text', 'bg', 4.5], ['text', 'surface', 4.5], ['text', 'surface-raised', 4.5], ['text', 'muted', 4.5],
  ['text-muted', 'bg', 4.5], ['text-muted', 'surface', 4.5], ['text-muted', 'muted', 4.5],
  ['text-subtle', 'bg', 3], ['text-subtle', 'surface', 3],
  ['accent-fg', 'accent', 4.5], ['accent-fg', 'accent-hover', 4.5],
  ['accent-text', 'bg', 4.5], ['accent-text', 'surface', 4.5], ['accent-text', 'accent-subtle', 4.5],
  ['ring', 'bg', 3], ['ring', 'surface', 3],
  // WCAG 1.4.11: a control's edge needs 3:1 when it is what shows where the control is.
  ['border-strong', 'bg', 3], ['border-strong', 'surface', 3],
  ['danger-fg', 'danger-hover', 4.5],
  ...STATUS.flatMap((s) => [[`${s}-fg`, s, 4.5], [`${s}-text`, 'bg', 4.5], [`${s}-text`, `${s}-subtle`, 4.5]]),
];
// Advisory pairs warn without failing. Empty for now; kept for pairs that are judgment calls.
const ADVISORY = [];

function resolved(preset, mode) {
  const ink = presets.ink;
  let colors = { ...ink.light.colors, ...status.light };
  if (mode === 'dark') colors = { ...colors, ...ink.dark.colors, ...status.dark };
  if (preset !== 'ink') {
    colors = { ...colors, ...presets[preset].light.colors };
    if (mode === 'dark') colors = { ...colors, ...presets[preset].dark.colors };
  }
  return colors;
}

// ─── Checks ────────────────────────────────────────────────────────────────────────────

function checkShape(errors) {
  const ink = presets.ink;
  const inkKeys = Object.keys(ink.light.colors).sort().join();
  if (Object.keys(ink.dark.colors).sort().join() !== inkKeys) errors.push('ink: light and dark define different colour tokens');
  for (const [name, p] of Object.entries(presets)) {
    for (const mode of ['light', 'dark']) {
      for (const k of Object.keys(p[mode].colors)) if (!(k in ink.light.colors)) errors.push(`${name} ${mode}: unknown colour token "${k}"`);
      for (const k of ['1', '2', '3']) if (!(k in p[mode].shadows)) errors.push(`${name} ${mode}: missing shadow level ${k}`);
    }
    // A preset's dark block has to replace every colour its light block sets, or light values leak into dark.
    if (name !== 'ink' && Object.keys(p.dark.colors).sort().join() !== Object.keys(p.light.colors).sort().join()) {
      errors.push(`${name}: light and dark must override the same colour tokens`);
    }
    for (const group of ['fonts', 'radius', 'density', 'motion']) {
      for (const k of Object.keys(p[group] ?? {})) if (!(k in ink[group])) errors.push(`${name}: unknown ${group} token "${k}"`);
    }
  }
  for (const k of Object.keys(status.dark)) if (!(k in status.light)) errors.push(`status dark: unknown token "${k}"`);
}

function checkContrast(errors, warnings) {
  const rows = [];
  for (const preset of Object.keys(presets)) {
    for (const mode of ['light', 'dark']) {
      const c = resolved(preset, mode);
      let worst = { margin: Infinity, label: '' };
      for (const [fg, bg, min] of PAIRS) {
        const r = contrast(c[fg], c[bg], c.bg);
        if (r / min < worst.margin) worst = { margin: r / min, label: `${fg} on ${bg} at ${r.toFixed(2)}:1` };
        if (r < min) errors.push(`${preset} ${mode}: ${fg} on ${bg} is ${r.toFixed(2)}:1, needs ${min}:1`);
      }
      for (const [fg, bg, min] of ADVISORY) {
        const r = contrast(c[fg], c[bg], c.bg);
        if (r < min) warnings.push(`${preset} ${mode}: ${fg} on ${bg} is ${r.toFixed(2)}:1 (WCAG 1.4.11 suggests ${min}:1 for control edges)`);
      }
      rows.push(`  ${`${preset} ${mode}`.padEnd(14)} ${PAIRS.length} pairs pass; tightest: ${worst.label}`);
    }
  }
  return rows;
}

// ─── useThemeCustomizer preset table ───────────────────────────────────────────────────
// The customizer derives values from each preset's neutrals, fonts and density. It is a
// copy-in composable with no access to this file, so build writes the table into it.

const CUSTOMIZER_PATH = path.join(ROOT, 'composables', 'useThemeCustomizer.ts');
const GEN_START = '// <generated:presets>';
const GEN_END = '// </generated:presets>';
const CUSTOMIZER_COLORS = ['bg', 'surface', 'surface-raised', 'muted', 'border', 'border-strong', 'text', 'text-muted', 'text-subtle', 'accent-text', 'ring'];

function customizerTable() {
  const key = (k) => (/^[a-z]+$/.test(k) ? k : `'${k}'`);
  const obj = (o) => `{ ${Object.entries(o).map(([k, v]) => `${key(k)}: '${v}'`).join(', ')} }`;
  const lines = ['const PRESETS = {'];
  for (const [name, p] of Object.entries(presets)) {
    const pick = (mode) => {
      const colors = { ...presets.ink[mode].colors, ...p[mode]?.colors };
      return Object.fromEntries(CUSTOMIZER_COLORS.map((k) => [k, colors[k]]));
    };
    lines.push(
      `  ${name}: {`,
      `    fonts: ${obj({ ...presets.ink.fonts, ...p.fonts })},`,
      `    density: ${obj({ ...presets.ink.density, ...p.density })},`,
      `    light: ${obj(pick('light'))},`,
      `    dark: ${obj(pick('dark'))},`,
      '  },',
    );
  }
  lines.push('} as const;');
  return lines.join('\n');
}

function withCustomizerTable(text) {
  const a = text.indexOf(GEN_START);
  const b = text.indexOf(GEN_END);
  if (a < 0 || b < a) throw new Error(`${GEN_START} … ${GEN_END} markers missing in useThemeCustomizer.ts`);
  const afterStart = text.indexOf('\n', a) + 1;
  return text.slice(0, afterStart) + customizerTable() + '\n' + text.slice(b);
}

function checkCustomizer(errors) {
  if (!fs.existsSync(CUSTOMIZER_PATH)) return;
  const current = fs.readFileSync(CUSTOMIZER_PATH, 'utf8').replace(/\r\n/g, '\n');
  if (current !== withCustomizerTable(current)) {
    errors.push('composables/useThemeCustomizer.ts preset table is out of date: run `node scripts/tokens.mjs build`');
  }
}

function checkCss(errors) {
  const current = fs.existsSync(CSS_PATH) ? fs.readFileSync(CSS_PATH, 'utf8').replace(/\r\n/g, '\n') : '';
  if (current !== buildCss()) errors.push('styles/tokens.css is out of date: run `node scripts/tokens.mjs build`');
}

// ─── Usage scan (the migration list) ───────────────────────────────────────────────────

const RENAMES = {
  background: 'bg',
  'text-secondary': 'text-muted',
  primary: 'accent',
  secondary: 'muted (fill) or text-muted (text)',
  emphasis: 'text',
  link: 'accent-text',
  'link-hover': 'accent-text',
  error: 'danger / danger-text',
};
const PALETTE = /^(?:(?:slate|gray|zinc|neutral|stone|red|orange|amber|yellow|lime|green|emerald|teal|cyan|sky|blue|indigo|violet|purple|fuchsia|pink|rose)-\d{2,3}|white|black)$/;
const UTILITY = /(?<![\w-])(bg|text|border(?:-[trblxy])?|ring|outline|fill|stroke|from|via|to|divide|placeholder|caret|decoration)-([a-z][a-z0-9-]*?)(?:\/\d+)?(?=[\s"'`:\]\)}]|$)/g;
const VAR = /var\(--color-([a-z0-9-]+)/g;
const HEX = /#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{3}\b/g;

function walk(dir) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = path.join(dir, e.name);
    return e.isDirectory() ? walk(p) : /\.(vue|ts)$/.test(e.name) ? [p] : [];
  });
}

function scanUsage(dirs) {
  const vocab = new Set(Object.keys({ ...presets.ink.light.colors, ...status.light }));
  const roots = dirs.length ? dirs.map((d) => path.resolve(d)) : [path.join(ROOT, 'components'), path.join(ROOT, 'composables')];
  // useThemeCustomizer carries the preset table as data (hex values, token names as strings).
  const files = roots.flatMap(walk).filter((f) => path.resolve(f) !== CUSTOMIZER_PATH);
  const report = [];
  const totals = { rename: 0, misuse: 0, palette: 0, unknown: 0, hex: 0 };
  for (const file of files) {
    // `// token-scan: off` … `// token-scan: on` marks strings that look like classes but are
    // data, such as a prop's accepted values.
    const text = fs.readFileSync(file, 'utf8').replace(/\/\/ token-scan: off[\s\S]*?\/\/ token-scan: on/g, '');
    const found = { rename: new Map(), misuse: 0, palette: new Map(), unknown: new Map(), hex: 0 };
    const bump = (map, key) => map.set(key, (map.get(key) ?? 0) + 1);
    for (const [, prop, name] of text.matchAll(UTILITY)) {
      if (name in RENAMES) bump(found.rename, `${prop}-${name}|${name}`);
      else if (prop === 'text' && name === 'muted') found.misuse++;
      else if (PALETTE.test(name)) bump(found.palette, `${prop}-${name}`);
    }
    for (const [, name] of text.matchAll(VAR)) {
      if (name in RENAMES) bump(found.rename, `--color-${name}|${name}`);
      else if (!vocab.has(name)) bump(found.unknown, `--color-${name}`);
    }
    found.hex = (text.match(HEX) ?? []).length;
    const sum = (m) => [...m.values()].reduce((a, b) => a + b, 0);
    const counts = { rename: sum(found.rename), misuse: found.misuse, palette: sum(found.palette), unknown: sum(found.unknown), hex: found.hex };
    if (Object.values(counts).every((n) => n === 0)) continue;
    for (const k of Object.keys(totals)) totals[k] += counts[k];
    const detail = [
      ...[...found.rename].map(([k, n]) => { const [use, name] = k.split('|'); return `${use} → ${RENAMES[name]} ×${n}`; }),
      found.misuse ? `text-muted → text-text-muted ×${found.misuse}` : '',
      ...[...found.palette].map(([k, n]) => `${k} (raw palette) ×${n}`),
      ...[...found.unknown].map(([k, n]) => `${k} (not in DESIGN.md) ×${n}`),
      found.hex ? `raw hex ×${found.hex}` : '',
    ].filter(Boolean);
    report.push(`  ${path.relative(ROOT, file).replace(/\\/g, '/')}\n      ${detail.join('\n      ')}`);
  }
  return { report, totals, files: files.length };
}

// ─── CLI ───────────────────────────────────────────────────────────────────────────────

const [cmd = 'check', ...flags] = process.argv.slice(2);
if (cmd === 'build') {
  fs.mkdirSync(path.dirname(CSS_PATH), { recursive: true });
  fs.writeFileSync(CSS_PATH, buildCss());
  console.log(`wrote ${path.relative(ROOT, CSS_PATH)}`);
  if (fs.existsSync(CUSTOMIZER_PATH)) {
    const raw = fs.readFileSync(CUSTOMIZER_PATH, 'utf8');
    const next = withCustomizerTable(raw.replace(/\r\n/g, '\n'));
    fs.writeFileSync(CUSTOMIZER_PATH, raw.includes('\r\n') ? next.replace(/\n/g, '\r\n') : next);
    console.log(`wrote the preset table in ${path.relative(ROOT, CUSTOMIZER_PATH)}`);
  }
} else if (cmd === 'check') {
  const errors = [];
  const warnings = [];
  checkShape(errors);
  const rows = checkContrast(errors, warnings);
  checkCss(errors);
  checkCustomizer(errors);
  console.log('Contrast, WCAG AA:');
  console.log(rows.join('\n'));
  for (const w of warnings) console.log(`  advisory: ${w}`);

  let usageFailed = false;
  if (flags.includes('--usage')) {
    const dirs = flags.flatMap((f, i) => (f === '--dir' && flags[i + 1] ? [flags[i + 1]] : []));
    const { report, totals, files } = scanUsage(dirs);
    console.log(`\nToken usage in ${files} files:`);
    console.log(report.length ? report.join('\n') : '  clean');
    console.log(
      `\n  ${totals.rename} old names, ${totals.misuse} text-muted misuses, ${totals.palette} raw palette, ` +
        `${totals.unknown} unknown tokens, ${totals.hex} raw hex`,
    );
    usageFailed = flags.includes('--strict') && Object.values(totals).some((n) => n > 0);
  }

  if (errors.length) {
    console.log(`\n${errors.length} error(s):\n  ${errors.join('\n  ')}`);
    process.exit(1);
  }
  if (usageFailed) process.exit(1);
  console.log('\nTokens OK.');
} else {
  console.log('usage: node scripts/tokens.mjs build | check [--usage [--dir <path>]...] [--strict]');
  process.exit(2);
}
